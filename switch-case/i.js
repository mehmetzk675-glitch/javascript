//switch-case


let sayı=prompt("lütfen 1 ile 5 arasında bir sayı giriniz:");

switch(sayı){
case "1":
    console.log("girdiğiniz sayi 1");
    break;
case "2":
    console.log("girdiğiniz sayı 2");
    break;
    case "3":
    console.log("girdiğiniz sayı 3");
    break;
case "4":
    console.log("girdiğiniz sayı 4");
    break;
case "5":
    console.log("girdiğiniz sayı 5");
    break;
    default:
        console.log("lütfen 1 ile 5 arasında bir sayı giriniz!");

}

